import { framesDir } from './lib.mjs';
import { timeline, actions } from './stop.mjs';
import { bracket } from './bracket-setup.mjs';
const { app, win } = await bracket();
const T = timeline(win, framesDir('measure-tool')); const A = actions(win, T);
await T.shot(); T.hold(900);
await A.clickLoc(win.locator('button[title="Measure between two surface points"]'));
T.hold(400);
await A.click({ x: 985, y: 360 });
T.hold(300);
await A.click({ x: 1215, y: 590 }, { wait: 1200 });
T.hold(1800);
await A.click({ x: 1120, y: 545 });
T.hold(300);
await A.click({ x: 1265, y: 565 }, { wait: 1200 });
T.hold(2500);
T.glide({ x: 1150, y: 250 }, 700); T.hold(800);
T.save();
await app.close();
